#!/usr/bin/env python3
"""
Generate the Emberbyte theme palettes.

Reads tools/palettes/palettes.json (12 themes, a dark and a light set of 14 colour roles each), applies the
contrast rules of docs/superpowers/specs/2026-10-17-expressive-redesign-design.md section 9.1 by nudging colours
away from their background, and writes:

  * a Kotlin file with one EmberbytePalette constant per theme and mode (default path below)
  * a Markdown report with the contrast numbers and every adjustment (default path below)

Usage (from the repository root):
    python tools/palettes/generate_palettes.py                 # write both files
    python tools/palettes/generate_palettes.py --check         # exit 1 if the files on disk differ from a fresh run
    python tools/palettes/generate_palettes.py --out-dir DIR   # write both files into DIR instead (for tests)

The nudging only ever changes lightness (hue and saturation stay), so a theme keeps its character.
"""
import argparse
import colorsys
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
JSON_PATH = os.path.join(HERE, "palettes.json")
KOTLIN_REL = "ui/design/src/main/kotlin/io/github/khaledbahaaeldin/emberbyte/ui/design/theme/palette/GeneratedPalettes.kt"
REPORT_REL = "docs/design/expressive/palettes-report.md"
ROLES = ["background", "surface", "surface2", "text", "muted", "primary", "onPrimary", "accent", "onAccent",
         "warn", "onWarn", "danger", "onDanger", "track"]


def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb2hex(c):
    return "#%02X%02X%02X" % tuple(max(0, min(255, round(v))) for v in c)


def lum(h):
    def ch(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = hex2rgb(h)
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def ratio(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def nudge(fg, bg, need):
    """Move fg's lightness away from bg until the contrast is enough. Returns (colour, changed)."""
    if ratio(fg, bg) >= need:
        return fg, False
    r, g, b = [v / 255 for v in hex2rgb(fg)]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    up = lum(bg) < 0.4
    for _ in range(100):
        l = min(1.0, l + 0.01) if up else max(0.0, l - 0.01)
        c = rgb2hex([v * 255 for v in colorsys.hls_to_rgb(h, l, s)])
        if ratio(c, bg) >= need:
            return c, True
        if l in (0.0, 1.0):
            break
    for c in ("#FFFFFF", "#000000", "#111111", "#FAFAFA"):
        if ratio(c, bg) >= need:
            return c, True
    return fg, True


# (foreground role, background role, needed ratio): text and marks rules of design section 9.1
RULES = [
    ("text", "background", 7.0), ("muted", "background", 4.5), ("muted", "surface", 4.5),
    ("text", "surface", 4.5), ("text", "surface2", 4.5),
    ("onPrimary", "primary", 4.5), ("onAccent", "accent", 4.5), ("onWarn", "warn", 4.5), ("onDanger", "danger", 4.5),
    ("primary", "background", 3.0), ("primary", "surface", 3.0), ("track", "primary", 3.0),
]


def fix(palette):
    p = dict(palette)
    adjustments = []
    for fg, bg, need in RULES:
        new, changed = nudge(p[fg], p[bg], need)
        if changed:
            adjustments.append("%s %s -> %s" % (fg, p[fg], new))
            p[fg] = new
    text_min = min(ratio(p[a], p[b]) for a, b, n in RULES if n >= 4.5)
    mark_min = min(ratio(p[a], p[b]) for a, b, n in RULES if n == 3.0)
    return p, adjustments, text_min, mark_min


def const_name(theme_id, mode):
    return "%s%s" % (theme_id.capitalize(), mode.capitalize())


def kotlin_color(h):
    return "Color(0xFF%s)" % h.lstrip("#").upper()


def build(themes):
    kt = ["// GENERATED by tools/palettes/generate_palettes.py from tools/palettes/palettes.json. Do not edit by hand.",
          "package io.github.khaledbahaaeldin.emberbyte.ui.design.theme.palette", "",
          "import androidx.compose.ui.graphics.Color", ""]
    rep = ["# Palette report", "",
           "Generated by `tools/palettes/generate_palettes.py`. Text needs 4.5:1 (hero text 7:1 on the background), marks and rings 3:1.", "",
           "| Theme | Mode | Min text | Min marks | Colours adjusted |", "|---|---|---|---|---|"]
    names = []
    for t in themes:
        for mode in ("dark", "light"):
            p, adj, tmin, gmin = fix(t[mode])
            n = const_name(t["id"], mode)
            names.append((t["id"], mode, n))
            kt.append("internal val %s = EmberbytePalette(" % n)
            for r in ROLES:
                kt.append("    %s = %s," % (r, kotlin_color(p[r])))
            kt.append(")")
            kt.append("")
            rep.append("| %s | %s | %.1f | %.1f | %s |" % (t["name"], mode, tmin, gmin, "; ".join(adj) if adj else "none"))
    kt.append("internal val GeneratedPalettes: Map<String, Pair<EmberbytePalette, EmberbytePalette>> = mapOf(")
    for t in themes:
        kt.append('    "%s" to (%s to %s),' % (t["id"], const_name(t["id"], "dark"), const_name(t["id"], "light")))
    kt.append(")")
    return "\n".join(kt) + "\n", "\n".join(rep) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out-dir")
    args = ap.parse_args()
    themes = json.load(open(JSON_PATH, encoding="utf-8"))
    for t in themes:
        for mode in ("dark", "light"):
            missing = [r for r in ROLES if r not in t[mode]]
            if missing:
                sys.exit("theme %s %s misses roles %s" % (t["id"], mode, missing))
    kotlin, report = build(themes)
    if args.out_dir:
        os.makedirs(args.out_dir, exist_ok=True)
        open(os.path.join(args.out_dir, "GeneratedPalettes.kt"), "w", encoding="utf-8", newline="\n").write(kotlin)
        open(os.path.join(args.out_dir, "palettes-report.md"), "w", encoding="utf-8", newline="\n").write(report)
        print("wrote %d palettes to %s" % (len(themes) * 2, args.out_dir))
        return
    kpath, rpath = os.path.join(ROOT, KOTLIN_REL), os.path.join(ROOT, REPORT_REL)
    if args.check:
        same = (os.path.exists(kpath) and open(kpath, encoding="utf-8").read() == kotlin and
                os.path.exists(rpath) and open(rpath, encoding="utf-8").read() == report)
        print("up to date" if same else "OUT OF DATE: run tools/palettes/generate_palettes.py")
        sys.exit(0 if same else 1)
    os.makedirs(os.path.dirname(kpath), exist_ok=True)
    open(kpath, "w", encoding="utf-8", newline="\n").write(kotlin)
    open(rpath, "w", encoding="utf-8", newline="\n").write(report)
    print("wrote", kpath, "and", rpath)


if __name__ == "__main__":
    main()
